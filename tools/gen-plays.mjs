// Writes the native play scripts (tests/native/*.play) whose moves depend on
// where the rules put things: the three lessons, Journey stage 1 played to its
// results and the Thirty Moves challenge played out. It replays the shipped
// rules (js/rules.js, js/content.js) from each level's seed in the order the
// script issues commands, so every click names the cell the item really
// landed on. Orders only draw from the rules stream when they spawn (30 ticks
// after a serve, 40 after an expiry): the scripts wait out each respawn
// before the next station tap, and play the move-limited challenge inside the
// first 45 s, so the run's random draws come in the same order as here.
//   node tools/gen-plays.mjs        (npm run plays)
import { writeFileSync } from 'node:fs';
import { createGame, applyCommand, advance, FAMILIES, hashString } from '../js/rules.js';
import { TUTORIALS, JOURNEY_LEVELS, CHALLENGES } from '../js/content.js';

const OUT = new URL('../tests/native/', import.meta.url);

function label(st, i) {
  const c = st.board[i];
  const fam = FAMILIES[c.family].name;
  if (c.kind === 'gen') return `${fam} station, cell ${i + 1}. Activate to generate.`;
  return `${FAMILIES[c.family].tiers[c.tier - 1]} (${fam} tier ${c.tier}), cell ${i + 1}`;
}

/** A round driven like the UI does it, writing the play lines. */
class Driver {
  constructor(level, lines) { this.level = level; this.st = createGame(level); this.lines = lines; this.id = 0; }
  click(i) { this.lines.push('frames 5', `click =${label(this.st, i)}`); }
  cmd(c) {
    const res = applyCommand(this.st, this.level, { id: 'g' + (++this.id), ...c });
    if (!res.ok) throw new Error(`${this.level.id}: ${JSON.stringify(c)} refused: ${res.reason}`);
    return res;
  }
  station(family) { return this.st.board.findIndex((c) => c && c.kind === 'gen' && c.family === family); }
  spawn(family) {
    const g = this.station(family);
    this.click(g);
    const res = this.cmd({ kind: 'spawn', gen: g });
    return res.events[0].cell;
  }
  /** Tap one item, then the other: they merge on the second. */
  merge(from, to) {
    this.click(from);
    this.click(to);
    this.cmd({ kind: 'merge', from, to });
    return to;
  }
  /** Spawns and merges up to `tier`; returns the cell holding the dish. */
  make(family, tier) {
    if (tier === 1) return this.spawn(family);
    const a = this.make(family, tier - 1);
    const b = this.make(family, tier - 1);
    return this.merge(a, b);
  }
  serve(cell) {
    const c = this.st.board[cell];
    const order = this.st.orders.find((o) => o.family === c.family && o.tier === c.tier);
    this.click(cell);
    this.lines.push('frames 5', 'click =Serve');
    this.cmd({ kind: 'submit', cell, order: order.id });
  }
  /** Waits out an order's 30-tick respawn (36 ticks of 6 frames). */
  waitRespawn() {
    this.lines.push('frames 220');
    for (let i = 0; i < 36 && this.st.phase === 'active'; i++) advance(this.st, this.level);
  }
}

const tutorialLevel = (t) => ({ id: t.id, kind: 'tutorial', seed: hashString(t.id), cols: 6, rows: 6, theme: 'hearth', tutorialId: t.id, ...t.level });

// --- the lessons, then Journey stage 1 to its results ------------------------------------------
{
  const lines = [
    '# Learn: the three lessons through the Play button (a fresh profile opens Learn), each played on its board',
    '# by taps on the cells and Serve; then Journey stage 1 played to "All orders served!" and the results.',
    '# Generated by tools/gen-plays.mjs (npm run plays).',
    'until 300 Kitchen Merge',
    'frames 30',
    'click =Play',
  ];
  for (const t of TUTORIALS) {
    lines.push('until 120 =Learn', 'frames 10', `click ${t.title}`, 'until 60 Mode Setup', 'frames 10', 'click =Start', 'until 60 =Hint', 'frames 30');
    const d = new Driver(tutorialLevel(t), lines);
    if (t.goal.kind === 'spawn') { d.spawn('grain'); d.spawn('grain'); }
    else if (t.goal.kind === 'merge') d.make('grain', 2);
    else {
      const o = d.st.orders[0];
      d.serve(d.make(o.family, o.tier));
    }
    if (t.id === 'learn-2') lines.push('frames 5', 'save lesson');
    lines.push('until 60 Lesson complete!');
  }
  lines.push('until 120 =Learn', 'frames 10', 'expect Lesson 3: Serve ✓', 'click =Back', 'until 60 =Play', 'frames 10', 'click =Journey', 'until 60 =Journey', 'frames 10');
  const level = JOURNEY_LEVELS[0];
  lines.push('click =Stage 1. Serve the orders in time.', 'until 60 Mode Setup', 'frames 10', 'click =Start', 'until 60 Serve 3 orders', 'frames 30');
  const d = new Driver(level, lines);
  while (d.st.phase === 'active') {
    const o = d.st.orders[0];
    d.serve(d.make(o.family, o.tier));
    if (d.st.phase === 'active') d.waitRespawn();
  }
  lines.push('until 120 All orders served!', 'frames 30', `expect Total: ${d.st.score.orders + d.st.score.streaks + d.st.score.efficiency}`, 'save results',
    'click =Next Stage', 'until 60 Stage 2', 'frames 10', 'click =Back', 'until 60 =Play', 'frames 10', 'expect Stage 2/40');
  writeFileSync(new URL('learn-journey.play', OUT), lines.join('\n') + '\n');
}

// --- Thirty Moves played out: merges, a refused merge, discards -------------------------------
{
  const c = CHALLENGES.find((x) => x.id === 'ch-moves');
  const lines = [
    '# Challenges › Thirty Moves played out by taps on the cells: spawns, merges up the chains, Serve when a dish',
    '# matches, Discard, until the moves run out; the results. At a desktop size (the wide layout with rails).',
    '# Generated by tools/gen-plays.mjs (npm run plays).',
    '# viewport 1280x800',
    'until 300 Kitchen Merge',
    'frames 30',
    'click =Challenges',
    'until 60 Thirty Moves',
    'frames 10',
    'click Thirty Moves',
    'until 60 Mode Setup',
    'frames 10',
    'click =Start',
    'until 60 =Free service',
    'frames 30',
  ];
  const d = new Driver(c.level, lines);
  let saved = false;
  while (d.st.phase === 'active') {
    // Serve a dish that matches an order; else merge a pair; else spawn (alternating families).
    const st = d.st;
    const serveCell = st.board.findIndex((x) => x && x.kind === 'item' && st.orders.some((o) => o.family === x.family && o.tier === x.tier));
    if (serveCell >= 0) { d.serve(serveCell); if (d.st.phase === 'active') d.waitRespawn(); continue; }
    let pair = null;
    for (let i = 0; i < st.board.length && !pair; i++) for (let j = i + 1; j < st.board.length && !pair; j++) {
      const a = st.board[i], b = st.board[j];
      if (a && b && a.kind === 'item' && b.kind === 'item' && a.family === b.family && a.tier === b.tier && a.tier < 5) pair = [i, j];
    }
    if (pair) { d.merge(pair[0], pair[1]); if (!saved) { lines.push('frames 20', 'save merge'); saved = true; } continue; }
    if (st.movesLeft === 2) {
      // Discard the oldest item: select it, then Discard.
      const i = st.board.findIndex((x) => x && x.kind === 'item');
      d.click(i);
      lines.push('frames 5', 'click =Discard');
      d.cmd({ kind: 'trash', cell: i });
      continue;
    }
    d.spawn(st.moves % 2 ? 'dairy' : 'grain');
  }
  if (d.st.orders.length && d.st.fulfilled === 0) console.warn('ch-moves: nothing served');
  // The streak bonus depends on the seconds between serves, so the total is not predicted here; the dishes are.
  lines.push('until 120 Out of moves', 'frames 30', `expect Dishes served`, 'expect Total:', 'save results', 'click =Back to Title', 'until 60 =Play');
  writeFileSync(new URL('challenge-moves.play', OUT), lines.join('\n') + '\n');
}
console.log('wrote tests/native/learn-journey.play, challenge-moves.play');
